#!/usr/bin/env python3
"""Export Unknown Horizons content for the Godot port (constants + building JSON)."""

from __future__ import annotations

import hashlib
import json
import re
import sys
from pathlib import Path

import yaml

REPO_ROOT = Path(__file__).resolve().parents[2]
GODOT_ROOT = REPO_ROOT / "godot"
OUT_DIR = GODOT_ROOT / "resources" / "exported"


def prod_line_id(key: str | int) -> int:
	if isinstance(key, int):
		return key
	digest = int(hashlib.sha1(key.encode("utf-8")).hexdigest(), 16)
	return int(digest % 2**31)


def parse_constants_py() -> dict[str, dict[str, int]]:
	text = (REPO_ROOT / "horizons" / "constants.py").read_text(encoding="utf-8")
	classes: dict[str, dict[str, int]] = {}
	current: str | None = None
	for line in text.splitlines():
		m = re.match(r"^class (\w+):", line)
		if m and m.group(1) in (
			"RES",
			"BUILDINGS",
			"UNITS",
			"PRODUCTIONLINES",
			"GROUND",
		):
			current = m.group(1)
			classes[current] = {}
			continue
		if current and re.match(r"^\t[A-Z_][A-Z0-9_]*\s*=", line):
			name, val = line.strip().split("=", 1)
			name = name.strip()
			val = val.split("#")[0].strip()
			if val == "None":
				continue
			try:
				classes[current][name] = int(val)
			except ValueError:
				pass
		if line.startswith("class ") and current and not line.startswith(f"class {current}"):
			if not line.startswith("class ") or line[6:].split("(")[0].split(":")[0] in classes:
				pass
	return classes


def emit_game_constants(classes: dict[str, dict[str, int]]) -> None:
	lines = [
		"# Generated by development/godot/export_content.py — do not edit by hand.",
		"extends Node",
		"",
	]
	for cls_name, members in classes.items():
		lines.append(f"const {cls_name} = {{")
		for name, value in sorted(members.items(), key=lambda x: x[0]):
			lines.append(f'\t"{name}": {value},')
		lines.append("}")
		lines.append("")
	(GODOT_ROOT / "scripts" / "autoload" / "game_constants.gd").write_text(
		"\n".join(lines), encoding="utf-8"
	)


def resolve_res_token(token, res_map: dict[str, int]):
	if isinstance(token, int):
		return token
	if isinstance(token, str) and token.startswith("RES."):
		name = token[4:]
		if name in res_map:
			return res_map[name]
		return token
	raise ValueError(f"Unknown resource token: {token!r}")


def export_building(yaml_path: Path, res_map: dict[str, int]) -> dict:
	data = yaml.safe_load(yaml_path.read_text(encoding="utf-8"))

	def fix_res_list(entries):
		out = []
		for entry in entries or []:
			out.append([resolve_res_token(entry[0], res_map), entry[1]])
		return out
	out = {
		"id_name": data.get("id"),
		"size_x": data.get("size_x", 1),
		"size_y": data.get("size_y", 1),
		"components": {},
	}
	for comp in data.get("components", []):
		if not isinstance(comp, dict):
			continue
		for key, value in comp.items():
			if key == "ProducerComponent":
				lines = {}
				for lk, lv in value.get("productionlines", {}).items():
					fixed = dict(lv)
					if "produces" in fixed:
						fixed["produces"] = fix_res_list(fixed["produces"])
					if "consumes" in fixed:
						fixed["consumes"] = fix_res_list(fixed["consumes"])
					lines[str(prod_line_id(lk))] = fixed
				out["components"]["Producer"] = {"productionlines": lines}
			elif key == "StorageComponent":
				for storage_type, cfg in value.items():
					slot_sizes = {}
					for rk, rv in cfg.get("slot_sizes", {}).items():
						slot_sizes[str(resolve_res_token(rk, res_map))] = rv
					fixed_cfg = dict(cfg)
					fixed_cfg["slot_sizes"] = slot_sizes
					out["components"]["Storage"] = {"type": storage_type, "config": fixed_cfg}
	return out


def main() -> int:
	OUT_DIR.mkdir(parents=True, exist_ok=True)
	classes = parse_constants_py()
	emit_game_constants(classes)

	buildings = {}
	production_line_ids: dict[str, int] = {}
	buildings_dir = REPO_ROOT / "content" / "objects" / "buildings"
	res_map = classes["RES"]
	for path in sorted(buildings_dir.glob("*.yaml")):
		buildings[path.stem] = export_building(path, res_map)
		data = yaml.safe_load(path.read_text(encoding="utf-8"))
		for comp in data.get("components", []):
			if not isinstance(comp, dict):
				continue
			prod = comp.get("ProducerComponent")
			if not prod:
				continue
			for key in prod.get("productionlines", {}).keys():
				if isinstance(key, int):
					continue
				pid = prod_line_id(key)
				production_line_ids[f"{path.stem}:{key}"] = pid

	(OUT_DIR / "production_line_ids.json").write_text(
		json.dumps(production_line_ids, indent=2, sort_keys=True), encoding="utf-8"
	)
	(OUT_DIR / "buildings.json").write_text(
		json.dumps(buildings, indent=2, sort_keys=True), encoding="utf-8"
	)
	(OUT_DIR / "constants.json").write_text(
		json.dumps(classes, indent=2, sort_keys=True), encoding="utf-8"
	)
	print(f"Exported {len(buildings)} buildings to {OUT_DIR}")
	return 0


if __name__ == "__main__":
	sys.exit(main())
